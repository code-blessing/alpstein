package org.codeblessing.alpstein.codegen.renderer.model.db

import org.codeblessing.alpstein.codegen.renderer.model.NameCase

/**
 * One column of a [DbTableModel], storing exactly one attribute of the item.
 *
 * The [columnName] is a SQL identifier and therefore a plain string, either declared by the
 * `dbItem` of the item or derived from the [attributeName].
 */
data class DbColumnModel(
    val attributeName: NameCase,
    val columnName: String,
    val sqlType: DbSqlType,
    /** The SQL enum type this column is declared with, `null` for every other column. */
    val enumTypeName: String?,
    val isNullable: Boolean,
    val isMultiple: Boolean,
    val isPrimaryKey: Boolean,
) {
    /**
     * Whether this column holds a SQL array. A list of values that have a flat relational
     * representation is stored as an array of them; only a list of nested items lands in a
     * single [DbSqlType.JSONB] value.
     */
    val isArray: Boolean = isMultiple && sqlType != DbSqlType.JSONB

    /**
     * The type this column is declared with: the SQL enum type of the enum it stores, or else
     * the name of its [sqlType], with the array suffix if it holds a list.
     */
    val sqlTypeName: String = (enumTypeName ?: sqlType.sqlTypeName) + if (isArray) "[]" else ""

    /**
     * Whether the bind parameter of this column has to be cast to [sqlTypeName] in the INSERT.
     * Both an array and a `jsonb` value are passed as their textual representation, which
     * PostgreSQL only accepts with an explicit cast.
     */
    val requiresParameterCast: Boolean = isArray || sqlType == DbSqlType.JSONB

    /**
     * Whether the database counts out the value of this column, i.e. it is an integer primary key.
     * Such a column is declared `GENERATED BY DEFAULT AS IDENTITY`, and `BY DEFAULT` rather than
     * `ALWAYS` so that a data import can still write keys of its own — the repository does not,
     * it inserts the key as `DEFAULT` and reads back what the identity handed out.
     */
    val isIdentity: Boolean = isPrimaryKey && sqlType == DbSqlType.INTEGER

    /**
     * The counterpart of [isIdentity] for a uuid primary key, which is declared
     * `DEFAULT gen_random_uuid()` so that the database hands out this key as well.
     */
    val hasRandomUuidDefault: Boolean = isPrimaryKey && sqlType == DbSqlType.UUID
}
